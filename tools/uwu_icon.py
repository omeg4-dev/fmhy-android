"""Build the UwU adaptive-icon foreground from the FMHY logo-uwu.svg (many flat <path>s).

    python3 tools/uwu_icon.py .cache/fmhy-edit/docs/public/logo-uwu.svg app/src/main/res/drawable/ic_launcher_uwu_foreground.xml

The wide wordmark is scaled to the 66dp adaptive-icon safe zone and centred on the 108dp canvas.
"""
import re, sys, pathlib, xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"
src, out = map(pathlib.Path, sys.argv[1:3])
root = ET.parse(src).getroot()
w, h = float(root.get("width")), float(root.get("height"))
scale = 66.0 / w
tx, ty = (108 - w * scale) / 2, (108 - h * scale) / 2
lines = []
for p in root.iter(NS + "path"):
    style = p.get("style", "")
    alpha = re.search(r"opacity:([.\d]+)", style)
    fill = p.get("fill", "#000000").lstrip("#")
    attrs = f'android:fillColor="#FF{fill.upper()}" android:pathData="{p.get("d")}"'
    if alpha and float(alpha.group(1)) < 1:
        attrs += f' android:fillAlpha="{float(alpha.group(1)):g}"'
    if "evenodd" in style:
        attrs += ' android:fillType="evenOdd"'
    lines.append(f"        <path {attrs} />")
out.write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Generated by tools/uwu_icon.py from logo-uwu.svg (FMHY). -->\n"
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="108dp" android:height="108dp"\n'
    '    android:viewportWidth="108" android:viewportHeight="108">\n'
    f'    <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}" '
    f'android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">\n'
    + "\n".join(lines)
    + "\n    </group>\n</vector>\n"
)
print(len(lines), "paths")
