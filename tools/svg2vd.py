"""Convert single-<path> Iconify SVGs to Android VectorDrawables (24dp, viewBox kept).

    python3 tools/svg2vd.py tools/icons-src app/src/main/res/drawable
File set__name.svg -> ic_<prefix>_<name>.xml. currentColor paths get #FF000000 (tint at use site);
explicitly coloured paths (twemoji) keep their colour.
"""
import re, sys, pathlib, xml.etree.ElementTree as ET

NAMES = {
    "carbon__logo-discord": "ic_link_discord", "carbon__logo-github": "ic_link_github",
    "carbon__logo-gitlab": "ic_link_gitlab", "gravity-ui__code": "ic_link_source",
    "mdi__telegram": "ic_link_telegram", "mdi__reddit": "ic_link_reddit", "carbon__logo-x": "ic_link_x",
    "mdi__mastodon": "ic_link_mastodon", "carbon__logo-bluesky": "ic_link_bluesky",
    "simple-icons__torbrowser": "ic_link_onion",
    "qlementine-icons__windows-24": "ic_platform_windows", "qlementine-icons__mac-fill-16": "ic_platform_macos",
    "fluent-mdl2__linux-logo-32": "ic_platform_linux", "material-symbols__android": "ic_platform_android",
    "simple-icons__ios": "ic_platform_ios", "fluent__globe-32-filled": "ic_platform_web",
    "simple-icons__docker": "ic_platform_docker",
    "twemoji__glowing-star": "ic_marker_top", "twemoji__star": "ic_marker_star",
    "twemoji__globe-with-meridians": "ic_marker_index", "twemoji__repeat-button": "ic_marker_section_link",
}
NS = "{http://www.w3.org/2000/svg}"
src, out = map(pathlib.Path, sys.argv[1:3])
out.mkdir(parents=True, exist_ok=True)
for f in sorted(src.glob("*.svg")):
    name = NAMES[f.stem]
    root = ET.parse(f).getroot()
    _, _, vw, vh = root.get("viewBox").split()
    paths = []
    for p in root.iter(NS + "path"):
        fill = p.get("fill", root.get("fill", "currentColor"))
        fill = "#FF000000" if fill in ("currentColor", None) else fill
        rule = p.get("fill-rule") or root.get("fill-rule")
        attrs = f'android:fillColor="{fill}" android:pathData="{p.get("d")}"'
        if rule == "evenodd":
            attrs += ' android:fillType="evenOdd"'
        paths.append(f"    <path {attrs} />")
    (out / f"{name}.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/svg2vd.py from Iconify; see THIRD_PARTY.md -->\n'
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" '
        f'android:height="24dp" android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n'
        + "\n".join(paths) + "\n</vector>\n")
    print(name, vw, vh, len(paths))
